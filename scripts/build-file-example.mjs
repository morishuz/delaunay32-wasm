import { readFile, readdir, writeFile } from "node:fs/promises";
import { fileURLToPath } from "node:url";
import path from "node:path";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const buildDirectory = path.join(root, "examples", "vite", "file-dist");
const assetsDirectory = path.join(buildDirectory, "assets");
const outputPath = path.join(root, "index.html");

// Vite deliberately emits the worker, WASM, JavaScript, and CSS separately.
// Inline them here so the checked-in demo also works when opened via file://.
const builtHtml = await readFile(path.join(buildDirectory, "index.html"), "utf8");
const scriptMatch = builtHtml.match(
  /<script\s+type="module"[^>]*\ssrc="([^"]+)"[^>]*><\/script>/,
);
const stylesheetMatch = builtHtml.match(
  /<link\s+rel="stylesheet"[^>]*\shref="([^"]+)"[^>]*>/,
);
if (scriptMatch === null || stylesheetMatch === null) {
  throw new Error("Unable to find the built demo entry script and stylesheet.");
}

const entryPath = resolveBuiltAsset(scriptMatch[1]);
const stylesheetPath = resolveBuiltAsset(stylesheetMatch[1]);
const assetNames = await readdir(assetsDirectory);
const workerNames = assetNames.filter(
  (name) => name.endsWith(".js") && path.join(assetsDirectory, name) !== entryPath,
);
const wasmNames = assetNames.filter((name) => name.endsWith(".wasm"));
if (workerNames.length !== 1 || wasmNames.length !== 1) {
  throw new Error(
    `Expected one worker and one WASM asset; found ${workerNames.length} workers and ${wasmNames.length} WASM files.`,
  );
}

const [entrySource, stylesheet, worker, wasm] = await Promise.all([
  readFile(entryPath, "utf8"),
  readFile(stylesheetPath, "utf8"),
  readFile(path.join(assetsDirectory, workerNames[0])),
  readFile(path.join(assetsDirectory, wasmNames[0])),
]);
const localBundle = JSON.stringify({
  workerBase64: worker.toString("base64"),
  wasmBase64: wasm.toString("base64"),
});

const output = builtHtml
  .replace(
    scriptMatch[0],
    `<script>globalThis.__DELAUNAY32_LOCAL_DEMO__=${localBundle};</script>\n` +
      `<script type="module">${escapeClosingTag(entrySource, "script")}</script>`,
  )
  .replace(
    stylesheetMatch[0],
    `<style>${escapeClosingTag(stylesheet, "style")}</style>`,
  )
  .replace(
    "<!doctype html>",
    "<!doctype html>\n<!-- Generated by `npm run example:file`; edit examples/vite instead. -->",
  );

await writeFile(outputPath, output);
console.log(`Wrote ${path.relative(root, outputPath)} (${output.length.toLocaleString()} bytes)`);

function resolveBuiltAsset(assetUrl) {
  const relativePath = assetUrl.replace(/^\.?\//, "");
  const resolved = path.resolve(buildDirectory, relativePath);
  if (!resolved.startsWith(`${buildDirectory}${path.sep}`)) {
    throw new Error(`Refusing to read an asset outside the demo build: ${assetUrl}`);
  }
  return resolved;
}

function escapeClosingTag(source, tagName) {
  return source.replace(new RegExp(`</${tagName}`, "giu"), `<\\/${tagName}`);
}
